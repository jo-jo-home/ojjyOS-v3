/*
 * ojjyOS v3 - X.509 certificates (RFC 5280) and server identity checks
 *
 * x509.c is a strict DER reader plus a certificate parser: it never reads
 * past the buffer, never allocates, and keeps spans that point into the
 * caller's DER bytes (the bytes must outlive the X509Cert). Unsupported
 * key or signature algorithms parse fine but come back as *_NONE, so the
 * chain check can name the real problem.
 *
 * x509_chain.c builds and checks a path from a server's certificate list
 * to a trusted root: host name (RFC 6125), validity against the clock,
 * signatures, CA flag, pathLen, keyUsage, extKeyUsage, dNSName/IPv4 name
 * constraints and unknown critical extensions. Every failure carries a
 * short reason for the user ("certificate expired on 2021-01-01").
 *
 * Built-in roots live in roots_data.c (generated by tools/mkroots.py):
 * subject DER + SubjectPublicKeyInfo only. Verification is public data, so
 * nothing here is constant time. Not reentrant (bignum scratch is static).
 *
 * ojjyOS - Created by Jonas Lee
 */
#ifndef _OJJY_X509_H
#define _OJJY_X509_H

#include "types.h"

typedef struct {
    const uint8_t *p;
    size_t len;
} X509Span;

enum { X509_KEY_NONE = 0, X509_KEY_RSA, X509_KEY_EC_P256, X509_KEY_EC_P384 };

enum {
    X509_SIG_NONE = 0,
    X509_SIG_RSA_PKCS1_SHA256,
    X509_SIG_RSA_PKCS1_SHA384,
    X509_SIG_RSA_PKCS1_SHA512,
    X509_SIG_RSA_PSS_SHA256,
    X509_SIG_RSA_PSS_SHA384,
    X509_SIG_RSA_PSS_SHA512,
    X509_SIG_ECDSA_SHA256,
    X509_SIG_ECDSA_SHA384,
};

/* keyUsage named bits (RFC 5280 4.2.1.3): bit i of the BIT STRING */
#define X509_KU_DIGITAL_SIGNATURE (1u << 0)
#define X509_KU_KEY_CERT_SIGN     (1u << 5)

typedef struct {
    int type;                   /* X509_KEY_* */
    X509Span n;                 /* RSA modulus, big-endian, no leading zero */
    uint32_t e;                 /* RSA public exponent */
    X509Span point;             /* EC: 0x04 || X || Y */
} X509Key;

typedef struct {
    X509Span der;               /* the whole certificate */
    X509Span tbs;               /* signed bytes (tbsCertificate, with header) */
    int version;                /* 1..3 */
    X509Span serial;
    int sig_alg;                /* X509_SIG_* (outer == inner, checked) */
    int pss_salt;               /* RSASSA-PSS salt length */
    X509Span sig;               /* signature bytes (BIT STRING payload) */
    X509Span issuer, subject;   /* full Name DER, compared byte for byte */
    int64_t not_before, not_after;  /* Unix seconds, UTC */
    X509Span spki;              /* full SubjectPublicKeyInfo DER */
    X509Key key;
    bool basic_present, ca;
    int path_len;               /* -1 = no limit */
    bool ku_present;
    uint32_t key_usage;         /* X509_KU_* */
    bool eku_present, eku_server_auth, eku_any;
    bool san_present;
    X509Span san;               /* GeneralNames contents */
    bool nc_present;
    X509Span name_constraints;  /* NameConstraints contents */
    bool unknown_critical;
} X509Cert;

/* Next TLV from *rest (rest advances). False at the end or on bad DER. */
bool x509_der_next(X509Span *rest, uint8_t *tag, X509Span *value);

/* Parse one DER certificate. False = malformed (or trailing bytes). */
bool x509_parse(const uint8_t *der, size_t len, X509Cert *out);
/* Parse a SubjectPublicKeyInfo (root store entries). */
bool x509_parse_spki(const uint8_t *der, size_t len, X509Key *out);
/* First CN (oid 2.5.4.3) or O (2.5.4.10) of a Name, printable ASCII/UTF-8. */
#define X509_ATTR_CN 3
#define X509_ATTR_O  10
bool x509_name_attr(const X509Span *name, int attr, char *out, size_t size);

/* Signature over msg with key: sig_alg says how (pss_salt < 0 = hash
 * length). ECDSA signatures are DER SEQUENCE { r, s } as in X.509 and
 * TLS. Curve/hash pairs: either curve with SHA-256 or SHA-384. */
bool x509_verify_message(int sig_alg, int pss_salt, const X509Key *key,
                         const uint8_t *msg, size_t msg_len,
                         const uint8_t *sig, size_t sig_len);
/* child's signature made by issuer_key */
bool x509_signed_by(const X509Cert *child, const X509Key *issuer_key);
/* Key size in bits (RSA modulus or curve) for strength checks. */
int x509_key_bits(const X509Key *key);

/* --- path building (x509_chain.c) --------------------------------- */

typedef struct {
    const uint8_t *subject;     /* Name DER */
    uint16_t subject_len;
    const uint8_t *spki;        /* SubjectPublicKeyInfo DER */
    uint16_t spki_len;
    const char *label;          /* for logs and the page-info popover */
} X509Root;

typedef enum {
    X509_OK = 0,
    X509_E_MALFORMED,
    X509_E_UNSUPPORTED,
    X509_E_NAME,
    X509_E_EXPIRED,
    X509_E_NOT_YET_VALID,
    X509_E_SELF_SIGNED,
    X509_E_UNKNOWN_ISSUER,
    X509_E_BAD_SIGNATURE,
    X509_E_NOT_CA,
    X509_E_PATH_LEN,
    X509_E_KEY_USAGE,
    X509_E_EKU,
    X509_E_CRITICAL,
    X509_E_NAME_CONSTRAINT,
    X509_E_WEAK_KEY,
    X509_E_TOO_MANY,
} X509Status;

#define X509_MAX_CHAIN  8       /* certificates accepted from a server */

typedef struct {
    const X509Root *roots;
    size_t root_count;
    int64_t now;                /* Unix seconds */
    int64_t slack;              /* clock tolerance in seconds (0 when synced) */
} X509Policy;

typedef struct {
    X509Status status;
    char reason[96];            /* user-facing, "" when verified */
    char subject[64];           /* leaf CN (or first DNS name) */
    char issuer[64];            /* leaf issuer CN/O */
    char root[64];              /* trust anchor label when verified */
    int depth;                  /* certificates used, leaf included */
} X509Result;

/* Verify a server's list (leaf first, then any order). host is the name
 * the user asked for (DNS name or dotted IPv4). */
X509Status x509_verify_chain(const X509Span *certs, size_t count, const char *host,
                             const X509Policy *policy, X509Result *result);
/* RFC 6125 host check against the leaf's subjectAltName only. */
bool x509_host_matches(const X509Cert *leaf, const char *host);

/* Built-in trust store (roots_data.c, generated). */
extern const X509Root x509_builtin_roots[];
extern const size_t x509_builtin_root_count;

#endif /* _OJJY_X509_H */
