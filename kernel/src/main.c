/*
 * Draw mouse cursor
 */
static void draw_cursor(int x, int y)
{
    static const uint8_t cursor[12] = {
        0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xFC,
        0xFE, 0xF0, 0xD8, 0x8C, 0x0C, 0x06
    };

    for (int row = 0; row < 12; row++) {
        for (int col = 0; col < 8; col++) {
            if (cursor[row] & (0x80 >> col)) {
                fb_put_pixel(x + col, y + row, COLOR_BLACK);
            }
        }
    }
    for (int row = 1; row < 11; row++) {
        for (int col = 1; col < 7; col++) {
            uint8_t inner = cursor[row] & (0x80 >> col);
            uint8_t left = cursor[row] & (0x80 >> (col - 1));
            if (inner && left) {
                fb_put_pixel(x + col, y + row, COLOR_WHITE);
            }
        }
    }
}

/*
 * Kernel main function
 */
void kernel_main(BootInfo *boot_info)
{
    g_boot_info = boot_info;

#ifndef __x86_64__
    /* Describe the machine from ACPI before anything else: the serial
     * driver needs to know whether a PL011 exists, and every other
     * driver asks the platform where its devices live. */
    platform_init(boot_info);
#endif

    /* Initialize serial first for debugging */
    serial_init(COM1_PORT);
    serial_printf("\n\n");
    serial_puts("      *             .           *      .\n");
    serial_puts("          /\\                   *       \n");
    serial_puts("         /  \\       /\\        .      *\n");
    serial_puts("        /    \\     /  \\    *        \n");
    serial_puts("   *   /      \\   /    \\       .      \n");
    serial_puts("      /        \\ /      \\        *   \n");
    serial_puts("     /   /\\             \\           \n");
    serial_puts("    /   /  \\   /\\        \\    .      \n");
    serial_puts("   /___/    \\ /  \\___     \\       *\n");
    serial_puts("  ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n");
    serial_puts("   ~   T a h o e  -  L i q u i d   ~    \n");
    serial_puts("  ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n\n");
    serial_puts(" ___     _     _     _    ___    ____ \n");
    serial_puts("/ _ \\   (_)   (_)   | |  / _ \\  / ___|\n");
    serial_puts("| | |   | |   | |  / _ \\ | | | | \\___ \\\n");
    serial_puts("| |_| _ | | _ | | | (_| | |_| |  ___)|\n");
    serial_puts("\\___/ (_)_/ (_)_/  \\__|  \\___/  |____/\n");
    serial_printf("\n");
    serial_printf("  ojjyOS v%s - the \"Make It Work\" release\n", OJJYOS_VERSION);
    serial_printf("  Created by %s\n", OJJYOS_AUTHOR);
    serial_printf("  A custom kernel - not based on Linux, BSD, Windows or macOS\n");
    serial_printf("~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n");
    serial_printf(" ~  ojjyOS  -  Tahoe Liquid Glass  ~\n");
    serial_printf("~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n\n");

#ifndef __x86_64__
    serial_printf("[PLATFORM] %s gic v%d gicd 0x%llx ecam 0x%llx\n",
        platform.name ? platform.name : "?",
        platform.gic_version,
        (unsigned long long)platform.gicd,
        (unsigned long long)platform.ecam);
#endif

    serial_printf("[BOOT] Framebuffer: %dx%d @ 0x%p\n",
        boot_info->fb_width, boot_info->fb_height, boot_info->fb_addr);

    /* Initialize framebuffer and show the splash */
    fb_init(boot_info);

    /* Initialize console early; the splash covers it during boot */
    console_init();
    console_set_colors(COLOR_TEXT, COLOR_CREAM);

    splash_render("Starting ojjyOS...", 3);

    /* Core initialization */
#ifdef __x86_64__
    gdt_init();
    splash_render("Loading CPU tables (GDT/IDT)...", 12);

    idt_init();
    splash_render("Setting up memory...", 22);

    pmm_init(boot_info);
    paging_init();
#else
    splash_render("Loading EL1 exception vectors...", 12);
    splash_render("Setting up memory...", 22);

    /* Reserve physical memory before installing owned supervisor mappings. */
    pmm_init(boot_info);
#endif
    user_arch_init();
    kheap_init();
#ifndef __x86_64__
    virtio_pci_console_init();
    /* Prefer virtio-gpu (any screen shape) over the 4:3-only ramfb. */
    if (virtio_gpu_display_init(boot_info)) {
        console_init();
        console_set_colors(COLOR_TEXT, COLOR_CREAM);
    }
#endif
    timer_init();
    splash_render("Bringing up drivers...", 38);

    /* Driver subsystem */
    driver_subsystem_init();
    input_init();
    net_init();     /* before device discovery: drivers attach to it */
    input_set_mouse_bounds(fb_get_width(), fb_get_height());

#ifdef __x86_64__
    ps2_keyboard_init();
    ps2_mouse_init();
    ata_init();
    rtc_init();
    driver_probe_all();
    block_cache_init();
#else
    a64_init(boot_info);
    driver_probe_all();
#endif
    splash_render("Mounting filesystems...", 55);

    /* Initialize filesystem */
    vfs_init();

    VfsOps *fs_ops = ojfs_init(embedded_fs, embedded_fs_len, &root_fs);
    if (fs_ops) {
        vfs_mount("/", fs_ops, root_fs, true);
        serial_printf("[BOOT] Root filesystem mounted (OJFS, %d bytes)\n",
            (int)embedded_fs_len);
    } else {
        serial_printf("[BOOT] WARNING: Failed to mount root filesystem\n");
    }

    VfsOps *ram_ops = ramfs_get_ops();
    void *users_fs = ramfs_create();
    void *library_fs = ramfs_create();

    if (ram_ops && users_fs && library_fs) {
        persist_instances[0] = users_fs;
        persist_instances[1] = library_fs;

        vfs_mount("/Users", ram_ops, users_fs, false);
        vfs_mount("/Library", ram_ops, library_fs, false);

        /* Restore the previous session's user data from the disk
         * (persistence). On a fresh disk there is no checkpoint yet:
         * seed the default files instead. */
        bool restored = false;
        if (block_available()) {
            restored = (persist_load(persist_instances, 2) == 0);
        } else {
            serial_printf("[BOOT] No data disk attached: changes will not persist\n");
        }

        if (!restored) {
            seed_user_data();
        }
        users_init();
    }
    proc_init();

    splash_render("Preparing applications...", 72);

    /* Initialize bundle system */
    bundle_init();
    bundle_register_builtin("com.ojjyos.about", about_app_handler);

    /* Enable interrupts */
    interrupts_enable();
    splash_render("Welcome to ojjyOS", 100);

    /* Boot complete: show the welcome banner on the live screen
     * (the splash rendered through the back buffer) */
    fb_use_backbuffer(false);
    console_clear();
    console_set_colors(COLOR_TEXT_LIGHT, BOOT_BG);
    for (int i = 0; i < (int)(sizeof(boot_scene) / sizeof(boot_scene[0])); i++) {
        console_printf("%s\n", boot_scene[i]);
    }
    console_printf("\n");
    console_set_colors(COLOR_SKY_BLUE, BOOT_BG);
    for (int i = 0; i < (int)(sizeof(boot_art) / sizeof(boot_art[0])); i++) {
        console_printf("%s\n", boot_art[i]);
    }
    console_printf("\n");
    console_set_colors(COLOR_OCEAN, BOOT_BG);
    console_printf("  Welcome to ojjyOS v%s\n", OJJYOS_VERSION);
    console_printf("  Created by %s\n\n", OJJYOS_AUTHOR);
    console_set_colors(COLOR_TEXT_LIGHT, BOOT_BG);
#ifdef __x86_64__
    console_printf("  [ OK ] CPU tables loaded (GDT/IDT)\n");
#else
    console_printf("  [ OK ] CPU vectors & GICv2 loaded (aarch64 EL1)\n");
#endif
    console_printf("  [ OK ] Memory: %d MB total, %d MB free (KHeap %d KB)\n",
        (int)(pmm_get_total_memory() / (1024 * 1024)),
        (int)(pmm_get_free_memory() / (1024 * 1024)),
        (int)(kheap_get_total() / 1024));
    console_printf("  [ OK ] Drivers: %d registered\n", driver_get_count());
    console_printf("  [ OK ] Root filesystem mounted (OJFS)\n");
    console_printf("  [ OK ] User filesystems mounted (RAMFS%s)\n",
        block_available() ? " + disk persistence" : ", no disk attached");
    console_printf("  [ OK ] Accounts: %d registered (active: %s)\n",
        users_count(), users_current_username());
    console_printf("  [ OK ] Process table: %d tasks active\n", proc_count());
    console_printf("  [ OK ] Keyboard and mouse ready\n");
    console_printf("  [ OK ] Interrupts enabled\n\n");
    console_set_colors(COLOR_OCEAN, BOOT_BG);
    for (int i = 0; i < (int)(sizeof(wave_art) / sizeof(wave_art[0])); i++) {
        console_printf("%s\n", wave_art[i]);
    }
    console_set_colors(COLOR_TEXT_LIGHT, BOOT_BG);
    console_printf("\n  Tip: type 'ui' to start the desktop, 'help' for commands\n\n");
    console_set_colors(COLOR_TEXT, COLOR_CREAM);

    /* Show available apps */
    cmd_apps();

    /* Instructions */
    console_printf("Type 'help' for available commands, 'tree' for the filesystem.\n\n");
    console_printf("> ");

    /* Automatically launch the macOS Tahoe desktop UI on boot
     * (Shift+Esc returns to the text console at any time) */
    cmd_ui(NULL);

    /* Cursor position */
    int32_t last_mx = -100, last_my = -100;

    /* Autosave bookkeeping */
    static uint64_t last_autosave_ms = 0;
    static bool autosave_announced = false;

    /* Main loop */
    serial_printf("[INIT] Entering main loop\n");

    while (1) {
        /* Power requests from the UI / shell / terminal */
        PowerRequest preq = system_get_request();
        if (preq != POWER_REQ_NONE) {
            system_clear_request();
            power_sequence(preq);  /* Returns only if saving failed */
        }

        /* Auto-save the writable filesystems every 30 seconds when
         * they have changed (plus on shutdown/reboot/sync) */
        uint64_t now_ms = timer_get_ticks();
        if (persist_instances[0] &&
            now_ms - last_autosave_ms >= 30000) {
            last_autosave_ms = now_ms;
            if (block_available() && !persist_save_active() && persist_any_dirty(persist_instances, 2) &&
                persist_begin_save(persist_instances, 2) == 0) {
                if (!autosave_announced) {
                    autosave_announced = true;
                    serial_printf("[PERSIST] Autosave active\n");
                }
            }
        }

        /* Leave input/rendering time between bounded autosave batches. */
        if (persist_save_active()) persist_step();

        /* Explicit sync request (e.g. from the Terminal) */
        if (system_sync_pending()) {
            save_persistent_state();
        }

#ifndef __x86_64__
        a64_poll_input();
#endif
        net_poll(timer_get_ticks());   /* DHCP/ARP/DNS/TCP timers */

        /* Process input events */
        for (unsigned budget = 0; budget < 128 && input_has_event(); budget++) {
            InputEvent event;
            input_poll_event(&event);
            /* Human input timing is real entropy for the DRBG (TLS keys). */
            {
                uint64_t mix[2] = { timer_get_ticks(), ((uint64_t)event.type << 32) ^ (uint64_t)event.motion.x ^
                                    ((uint64_t)event.motion.y << 16) ^ (uint64_t)event.key.keycode };
                random_add_entropy(mix, sizeof(mix));
            }

            if (ui_mode) {
                switch (event.type) {
                    case INPUT_EVENT_KEY_PRESS:
                    case INPUT_EVENT_KEY_REPEAT:
                        if (event.key.keycode == KEY_ESCAPE &&
                            (event.key.modifiers & INPUT_MOD_SHIFT) &&
                            !compositor_overlay_active()) {
                            ui_mode = false;
                            /* Console draws straight to the live screen */
                            fb_use_backbuffer(false);
                            console_clear();
                            console_printf("Type 'help' for available commands.\n\n> ");
                            break;
                        }
                        compositor_handle_key(event.key.keycode, event.key.ascii, event.key.modifiers);
                        break;
                    case INPUT_EVENT_KEY_RELEASE:
                        compositor_handle_key_release(event.key.keycode, event.key.modifiers);
                        break;
                    case INPUT_EVENT_MOUSE_MOVE:
                        if (event.motion.absolute) compositor_handle_mouse_absolute(event.motion.x, event.motion.y);
                        else compositor_handle_mouse_move(event.motion.dx, event.motion.dy);
                        break;
                    case INPUT_EVENT_MOUSE_BUTTON_DOWN: {
                        if (event.button.absolute) compositor_handle_mouse_absolute(event.button.x, event.button.y);
                        /* Hit-test at the position the user actually sees
                         * (the compositor applies the mouse speed setting) */
                        int32_t cx = 0, cy = 0;
                        compositor_get_cursor(&cx, &cy);
                        if (event.button.button == MOUSE_BUTTON_RIGHT) {
                            compositor_handle_right_click(cx, cy);
                        } else {
                            compositor_handle_mouse(cx, cy, true, false);
                        }
                        break;
                    }
                    case INPUT_EVENT_MOUSE_BUTTON_UP: {
                        if (event.button.absolute) compositor_handle_mouse_absolute(event.button.x, event.button.y);
                        int32_t cx = 0, cy = 0;
                        compositor_get_cursor(&cx, &cy);
                        if (event.button.button != MOUSE_BUTTON_RIGHT) {
                            compositor_handle_mouse(cx, cy, false, true);
                        }
                        break;
                    }
                    case INPUT_EVENT_MOUSE_SCROLL:
                        compositor_handle_scroll(event.scroll.dx, event.scroll.dy);
                        break;
                    default:
                        break;
                }
            } else {
                switch (event.type) {
                    case INPUT_EVENT_KEY_PRESS:
                    case INPUT_EVENT_KEY_REPEAT:
                        if (event.key.ascii) {
                            if (event.key.ascii == '\n') {
                                console_putc('\n');
                                process_command();
                                console_printf("> ");
                            } else if (event.key.ascii == '\b') {
                                if (cmd_pos > 0) {
                                    cmd_pos--;
                                    console_putc('\b');
                                }
                            } else if (cmd_pos < (int)sizeof(cmd_buffer) - 1) {
                                cmd_buffer[cmd_pos++] = event.key.ascii;
                                console_putc(event.key.ascii);
                            }
                        }
                        break;

                    case INPUT_EVENT_MOUSE_BUTTON_DOWN:
                        /* Could trigger app launch on click in future */
                        break;

                    default:
                        break;
                }
            }
        }

        if (ui_mode) {
            compositor_tick(timer_get_ticks());
        } else {
            /* Update mouse cursor */
            int32_t mx, my;
            input_get_mouse_position(&mx, &my);

            if (mx != last_mx || my != last_my) {
                if (last_mx >= 0 && last_my >= 0) {
                    fb_fill_rect(last_mx, last_my, 12, 12, COLOR_CREAM);
                }
                draw_cursor(mx, my);
                last_mx = mx;
                last_my = my;
            }
        }

        hlt();
    }
}
