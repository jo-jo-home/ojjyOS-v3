/*
 * Start UI desktop
 */
static void cmd_ui(const char *arg)
{
    if (!ui_initialized) {
        compositor_init(fb_get_width(), fb_get_height());
        ui_initialized = true;
    }
    /* Shift+Esc switches to direct console drawing; restore buffering on
     * every UI entry, not just the first compositor initialization. */
    fb_use_backbuffer(true);

    /* "ui dark" / "ui light" pick an appearance; plain "ui" (and boot) keep
     * the saved one, which compositor_init already applied. */
    if (arg && (strcmp(arg, "dark") == 0 || strcmp(arg, "light") == 0)) {
        bool use_dark = strcmp(arg, "dark") == 0;
        if (use_dark != settings_get()->dark_mode) compositor_toggle_appearance();
    }

    compositor_set_active_app("Finder");
    compositor_open_default_apps();

    ui_mode = true;
    console_clear();
}

/*
 * Save persistent state (if a data disk is attached).
 */
static bool save_persistent_state(void)
{
    if (!persist_instances[0]) return true;
    if (block_available()) {
        return persist_save(persist_instances, 2) == 0;
    }
    return !persist_any_dirty(persist_instances, 2);
}

