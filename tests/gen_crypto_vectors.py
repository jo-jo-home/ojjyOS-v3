#!/usr/bin/env python3
"""Generate tests/crypto_vectors.h from independent implementations:
Python hashlib/hmac (SHA-256, HMAC, HKDF, HKDF-Expand-Label) and the
OpenSSL CLI (ChaCha20, Poly1305, X25519). Created by Jonas Lee.
Run: python3 tests/gen_crypto_vectors.py > tests/crypto_vectors.h
"""
import hashlib
import hmac
import os
import random
import subprocess
import tempfile

rng = random.Random(20261017)


def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))


def c_bytes(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data) or "0"
    return f"static const uint8_t {name}[] = {{{body}}};\nstatic const size_t {name}_len = {len(data)};\n"


def hkdf_extract(salt, ikm):
    return hmac.new(salt or bytes(32), ikm, hashlib.sha256).digest()


def hkdf_expand(prk, info, length):
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:length]


def expand_label(secret, label, context, length):
    full = b"tls13 " + label.encode()
    info = length.to_bytes(2, "big") + bytes([len(full)]) + full + bytes([len(context)]) + context
    return hkdf_expand(secret, info, length)


def openssl(args, data=b""):
    return subprocess.run(["openssl"] + args, input=data, capture_output=True, check=True).stdout


out = ["/* Generated by tests/gen_crypto_vectors.py - do not edit. Created by Jonas Lee. */\n"]
msg = bytes(range(256)) * 2
for n in [0, 3, 55, 56, 63, 64, 65, 119, 200, 512]:
    out.append(c_bytes(f"sha_in_{n}", msg[:n]))
    out.append(c_bytes(f"sha_out_{n}", hashlib.sha256(msg[:n]).digest()))
out.append("#define SHA_CASES(X) " + " ".join(f"X({n})" for n in [0, 3, 55, 56, 63, 64, 65, 119, 200, 512]) + "\n")

key, data = rb(100), rb(77)
out.append(c_bytes("hmac_key", key) + c_bytes("hmac_data", data) +
           c_bytes("hmac_out", hmac.new(key, data, hashlib.sha256).digest()))

secret = rb(32); ctx = hashlib.sha256(b"transcript").digest()
out.append(c_bytes("label_secret", secret) + c_bytes("label_ctx", ctx) +
           c_bytes("label_key16", expand_label(secret, "key", b"", 16)) +
           c_bytes("label_iv12", expand_label(secret, "iv", b"", 12)) +
           c_bytes("label_derived", expand_label(secret, "derived", hashlib.sha256(b"").digest(), 32)) +
           c_bytes("label_cfin", expand_label(secret, "c hs traffic", ctx, 32)))

# ChaCha20 keystream via OpenSSL (IV = 32-bit LE counter || 96-bit nonce)
ck, cn = rb(32), rb(12)
plain = rb(300)
iv = (7).to_bytes(4, "little") + cn
out.append(c_bytes("chacha_key", ck) + c_bytes("chacha_nonce", cn) + c_bytes("chacha_plain", plain) +
           c_bytes("chacha_cipher", openssl(["enc", "-chacha20", "-K", ck.hex(), "-iv", iv.hex()], plain)))

# Poly1305 via OpenSSL MAC
for i, n in enumerate([0, 1, 16, 33, 131]):
    pk, pm = rb(32), rb(n)
    with tempfile.NamedTemporaryFile(delete=False) as f:
        f.write(pm)
    tag = openssl(["mac", "-macopt", "hexkey:" + pk.hex(), "-in", f.name, "-binary", "POLY1305"])
    os.unlink(f.name)
    out.append(c_bytes(f"poly_key_{i}", pk) + c_bytes(f"poly_msg_{i}", pm) + c_bytes(f"poly_tag_{i}", tag))
out.append("#define POLY_CASES(X) X(0) X(1) X(2) X(3) X(4)\n")

# X25519 via OpenSSL: raw private -> public, and a shared secret
der_prefix = bytes.fromhex("302e020100300506032b656e04220420")
pub_prefix = bytes.fromhex("302a300506032b656e032100")
with tempfile.TemporaryDirectory() as d:
    keys = []
    for name in ["a", "b"]:
        raw = rb(32)
        path = os.path.join(d, name + ".der")
        open(path, "wb").write(der_prefix + raw)
        pub = openssl(["pkey", "-inform", "DER", "-in", path, "-pubout", "-outform", "DER"])[-32:]
        keys.append((raw, pub, path))
    peer = os.path.join(d, "bpub.der")
    open(peer, "wb").write(pub_prefix + keys[1][1])
    shared = openssl(["pkeyutl", "-derive", "-keyform", "DER", "-inkey", keys[0][2], "-peerform", "DER",
                      "-peerkey", peer])
out.append(c_bytes("x_priv_a", keys[0][0]) + c_bytes("x_pub_a", keys[0][1]) +
           c_bytes("x_priv_b", keys[1][0]) + c_bytes("x_pub_b", keys[1][1]) + c_bytes("x_shared", shared))
print("".join(out))
