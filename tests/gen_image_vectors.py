#!/usr/bin/env python3
"""Generate tests/image_vectors.h: zlib/gzip streams and small PNG/GIF files
(made with Python's zlib/gzip and Pillow) plus their expected ARGB pixels,
so the kernel's inflate, PNG and GIF decoders are checked against
independent encoders. Created by Jonas Lee."""
import gzip
import io
import zlib
from pathlib import Path
from PIL import Image

out = []


def arr(name, data):
    out.append(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(data), 20):
        out.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    out.append("};")
    out.append(f"static const unsigned {name}_len = {len(data)};")


def pixels(name, img):
    img = img.convert("RGBA")
    vals = []
    for (r, g, b, a) in list(img.getdata()):
        vals.append((a << 24) | (r << 16) | (g << 8) | b)
    out.append(f"static const unsigned int {name}[] = {{")
    for i in range(0, len(vals), 8):
        out.append("    " + ",".join(f"0x{v:08X}u" for v in vals[i:i + 8]) + ",")
    out.append("};")


text = (b"ojjyOS Web inflates pages and pictures. " * 40) + bytes(range(256))
arr("zlib_text", zlib.compress(text, 9))
arr("zlib_fixed", zlib.compress(b"hello hello hello hello", 1))
arr("gzip_text", gzip.compress(text, 6, mtime=0))
arr("plain_text", text)

# RGBA with partial alpha, 7x5
rgba = Image.new("RGBA", (7, 5))
for y in range(5):
    for x in range(7):
        rgba.putpixel((x, y), (x * 36, y * 60, (x * y * 13) % 256, 40 + x * 30))
buf = io.BytesIO(); rgba.save(buf, "PNG"); arr("png_rgba", buf.getvalue()); pixels("png_rgba_px", rgba)
# RGB interlaced
rgb = Image.new("RGB", (9, 11))
for y in range(11):
    for x in range(9):
        rgb.putpixel((x, y), ((x * 29) % 256, (y * 23) % 256, (x + y) * 10 % 256))
buf = io.BytesIO(); rgb.save(buf, "PNG", interlace=1); arr("png_interlaced", buf.getvalue()); pixels("png_interlaced_px", rgb)
# palette with transparency, 6x4
pal = Image.new("P", (6, 4))
pal.putpalette([255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 0] + [0] * (252 * 3))
for y in range(4):
    for x in range(6):
        pal.putpixel((x, y), (x + y) % 4)
buf = io.BytesIO(); pal.save(buf, "PNG", transparency=2); arr("png_palette", buf.getvalue())
pixels("png_palette_px", Image.open(io.BytesIO(buf.getvalue())).convert("RGBA"))
# greyscale 1-bit
g1 = Image.new("1", (10, 3))
for y in range(3):
    for x in range(10):
        g1.putpixel((x, y), 1 if (x + y) % 3 == 0 else 0)
buf = io.BytesIO(); g1.save(buf, "PNG"); arr("png_grey1", buf.getvalue()); pixels("png_grey1_px", g1)
# GIF (palette, transparency)
gif = Image.new("P", (8, 6))
gif.putpalette([10, 20, 30, 200, 100, 50, 0, 255, 0] + [0] * (253 * 3))
for y in range(6):
    for x in range(8):
        gif.putpixel((x, y), (x * 3 + y) % 3)
buf = io.BytesIO(); gif.save(buf, "GIF", transparency=1); arr("gif_small", buf.getvalue())
pixels("gif_small_px", Image.open(io.BytesIO(buf.getvalue())).convert("RGBA"))

# JPEG: the same picture as baseline and progressive (identical coefficients)
pic = Image.new("RGB", (45, 29))
for y in range(29):
    for x in range(45):
        pic.putpixel((x, y), ((x * 5) % 256, (y * 8) % 256, ((x + y) * 3) % 256))
for name, prog, sub in [("jpg_base", False, 2), ("jpg_prog", True, 2), ("jpg_prog444", True, 0)]:
    buf = io.BytesIO(); pic.save(buf, "JPEG", quality=88, progressive=prog, subsampling=sub); arr(name, buf.getvalue())
buf = io.BytesIO(); pic.save(buf, "JPEG", quality=88, progressive=False, subsampling=0); arr("jpg_base444", buf.getvalue())
grey = pic.convert("L")
buf = io.BytesIO(); grey.save(buf, "JPEG", quality=80, progressive=True); arr("jpg_prog_grey", buf.getvalue())
buf = io.BytesIO(); grey.save(buf, "JPEG", quality=80, progressive=False); arr("jpg_base_grey", buf.getvalue())

# WebP: lossy, lossy + alpha, lossless (+ libwebp's own decode as the reference)
photo = Image.new("RGBA", (37, 23))
for y in range(23):
    for x in range(37):
        photo.putpixel((x, y), ((x * 7) % 256, (y * 11) % 256, ((x * y) * 3) % 256, 255 if x < 20 else (x * 12) % 256))
for name, kw, mode in [("webp_lossy", dict(quality=80), "RGB"), ("webp_alpha", dict(quality=80), "RGBA"),
                       ("webp_lossless", dict(lossless=True), "RGBA")]:
    buf = io.BytesIO(); photo.convert(mode).save(buf, "WEBP", **kw); arr(name, buf.getvalue())
    pixels(name + "_px", Image.open(io.BytesIO(buf.getvalue())).convert("RGBA"))
big = Image.new("RGB", (64, 48))
for y in range(48):
    for x in range(64):
        big.putpixel((x, y), (int(128 + 100 * ((x - 32) / 32.0)) % 256, (y * 5) % 256, (x * y) % 256))
buf = io.BytesIO(); big.save(buf, "WEBP", quality=40, method=6); arr("webp_mb", buf.getvalue())
pixels("webp_mb_px", Image.open(io.BytesIO(buf.getvalue())).convert("RGBA"))

Path(__file__).with_name("image_vectors.h").write_text(
    "/* Generated by tests/gen_image_vectors.py (Python zlib/gzip + Pillow). Do not edit. */\n" + "\n".join(out) + "\n")
print("wrote image_vectors.h")
