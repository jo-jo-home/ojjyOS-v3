#!/usr/bin/env python3
"""Generate tests/jpeg_vectors.h: small synthetic JPEGs (made with Pillow)
and Pillow's own decoded pixels for comparison. Created by Jonas Lee."""
import io, math, random
from pathlib import Path
from PIL import Image

def smooth(w, h, seed):
    """Low-frequency colour: chroma upsampling method barely matters."""
    im = Image.new('RGB', (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = (int(128 + 100 * math.sin(x / 19 + seed)), int(128 + 100 * math.cos(y / 13 + seed)),
                        int(60 + 3 * x + 2 * y) & 255)
    return im

def picture(w, h, seed, gray=False):
    rnd = random.Random(seed)
    im = Image.new('RGB', (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            r = int(128 + 120 * math.sin(x / 7 + seed))
            g = int(128 + 120 * math.cos(y / 5 + seed))
            b = (x * 9 + y * 5 + rnd.randint(0, 20)) & 255
            px[x, y] = (r, g, b)
    return im.convert('L').convert('RGB') if gray else im

cases = [
    ('s420', smooth(37, 23, 1), dict(quality=90, subsampling=2)),
    ('s444', picture(24, 16, 2), dict(quality=95, subsampling=0)),
    ('s422', smooth(33, 17, 3), dict(quality=85, subsampling=1)),
    ('gray', picture(20, 12, 4, True).convert('L'), dict(quality=90)),
    ('rst', smooth(40, 32, 5), dict(quality=80, subsampling=2, restart_marker_blocks=1)),
    ('rst444', picture(40, 32, 6), dict(quality=90, subsampling=0, restart_marker_blocks=2)),
]
out = ['/* Generated by tests/gen_jpeg_vectors.py - do not edit. Created by Jonas Lee. */', '#include "types.h"', '']
names = []
for name, im, kw in cases:
    buf = io.BytesIO()
    try:
        im.save(buf, 'JPEG', optimize=False, progressive=False, **kw)
    except TypeError:
        kw.pop('restart_marker_blocks', None)
        im.save(buf, 'JPEG', optimize=False, progressive=False, **kw)
    data = buf.getvalue()
    ref = Image.open(io.BytesIO(data)).convert('RGB')
    w, h = ref.size
    out.append(f'static const uint8_t jpg_{name}[] = {{' + ','.join(str(b) for b in data) + '};')
    out.append(f'static const uint32_t ref_{name}[] = {{' + ','.join(str(r << 16 | g << 8 | b) for r, g, b in list(ref.getdata())) + '};')
    names.append((name, w, h, kw.get('subsampling', 0) == 2 or name == 'rst'))
out.append('typedef struct { const char *name; const uint8_t *jpg; unsigned len; const uint32_t *ref; int w, h; int subsampled; } JpegVector;')
out.append('static const JpegVector jpeg_vectors[] = {')
for name, w, h, sub in names:
    out.append(f'    {{ "{name}", jpg_{name}, sizeof(jpg_{name}), ref_{name}, {w}, {h}, {int(sub)} }},')
out.append('};')
Path(__file__).with_name('jpeg_vectors.h').write_text('\n'.join(out) + '\n')
print('wrote', len(names), 'vectors')
