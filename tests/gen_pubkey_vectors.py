#!/usr/bin/env python3
"""Generate tests/pubkey_vectors.h from independent implementations:
Python hashlib (SHA-384/512) and the OpenSSL CLI (RSA PKCS#1/PSS, ECDSA
P-256/P-384, plus big-integer modexp/reduce/inverse known answers).
Created by Jonas Lee.
Run: python3 tests/gen_pubkey_vectors.py > tests/pubkey_vectors.h
"""
import hashlib
import os
import random
import subprocess
import tempfile

rng = random.Random(20261018)
WORK = tempfile.mkdtemp(prefix="ojjy-pubkey-")


def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))


def c_bytes(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data) or "0"
    return f"static const uint8_t {name}[] = {{{body}}};\nstatic const size_t {name}_len = {len(data)};\n"


def run(args, data=b""):
    return subprocess.run(["openssl"] + args, input=data, capture_output=True, check=True).stdout


def text(args, data=b""):
    return subprocess.run(["openssl"] + args, input=data, capture_output=True, check=True).stdout.decode()


out = ["/* Generated by tests/gen_pubkey_vectors.py - do not edit. Created by Jonas Lee. */\n",
       "#include \"types.h\"\n"]

# ------------------------------------------------------------------ SHA-384/512
msg = bytes(range(256)) * 2
lengths = [0, 3, 55, 111, 112, 113, 127, 128, 200, 512, 1000]
out.append("#define SHA5_CASES(X) " + " ".join(f"X({n})" for n in lengths) + "\n")
for n in lengths:
    out.append(c_bytes(f"sha5_in_{n}", msg[:n]))
    out.append(c_bytes(f"sha384_out_{n}", hashlib.sha384(msg[:n]).digest()))
    out.append(c_bytes(f"sha512_out_{n}", hashlib.sha512(msg[:n]).digest()))

# ------------------------------------------------------------------ bignum
# modexp / reduce / inverse known answers from Python's exact arithmetic.
bn_vectors = []
for i in range(6):
    bits = [256, 512, 1024, 2048, 3072, 4096][i]
    a = rng.randrange(1 << (bits - 1), 1 << bits)
    m = rng.randrange(1 << (bits - 1), 1 << bits) | 1 | (1 << (bits - 1))
    e = 65537
    bn_vectors.append((a, e, m))
out.append("#define BN_CASES(X) " + " ".join(f"X({i})" for i in range(len(bn_vectors))) + "\n")
for i, (a, e, m) in enumerate(bn_vectors):
    red = (a % m) or 1                       # bn_mod_exp requires base < modulus
    out.append(c_bytes(f"bn_a_{i}", red.to_bytes((red.bit_length() + 7) // 8 or 1, "big")))
    out.append(c_bytes(f"bn_m_{i}", m.to_bytes((m.bit_length() + 7) // 8, "big")))
    out.append(c_bytes(f"bn_exp_{i}", e.to_bytes(4, "big")))
    out.append(c_bytes(f"bn_want_{i}", pow(a, e, m).to_bytes((m.bit_length() + 7) // 8, "big")))
# inverse mod a 256-bit prime (P-256 order) and reduce mod it
order = int.from_bytes(bytes.fromhex(
    "ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551"), "big")
inv_in = rng.randrange(2, order)
out.append(c_bytes("bn_p_ord", order.to_bytes(32, "big")))
out.append(c_bytes("bn_inv_in", inv_in.to_bytes(32, "big")))
out.append(c_bytes("bn_inv_want", pow(inv_in, order - 2, order).to_bytes(32, "big")))
red_in = rng.randrange(order, 1 << 400)
out.append(c_bytes("bn_red_in", red_in.to_bytes(50, "big")))
out.append(c_bytes("bn_red_want", (red_in % order).to_bytes(32, "big")))

# ------------------------------------------------------------------ RSA
# message fixed for all RSA/ECDSA cases
doc = b"ojjyOS v3 public key verification test vector. Created by Jonas Lee.\n"
out.append(c_bytes("doc", doc))

def gen_rsa(bits, tag):
    key = os.path.join(WORK, f"rsa-{tag}.pem")
    run(["genrsa", "-out", key, str(bits)])
    n = int(text(["rsa", "-in", key, "-noout", "-modulus"]).split("=")[1].strip(), 16)
    return key, n

rsa_cases = []      # (name, bits, key, n, hash_name, pss)
for bits in [2048, 3072, 4096]:
    key, n = gen_rsa(bits, f"pkcs1-{bits}")
    rsa_cases.append((f"pkcs1_{bits}", bits, key, n, "sha256", False))
key2048, n2048 = gen_rsa(2048, "aux")  # separate key for 384/512/PSS cases
rsa_cases.append(("pkcs1_384", 2048, key2048, n2048, "sha384", False))
rsa_cases.append(("pkcs1_512", 2048, key2048, n2048, "sha512", False))
rsa_cases.append(("pss_2048", 2048, key2048, n2048, "sha256", True))
rsa_cases.append(("pss_4096", 4096, [c for c in rsa_cases if c[1] == 4096][0][2],
                  [c for c in rsa_cases if c[1] == 4096][0][3], "sha384", True))
wrong_key, wrong_n = gen_rsa(2048, "wrong")

for name, bits, key, n, hash_name, pss in rsa_cases:
    args = ["dgst", f"-{hash_name}", "-sign", key]
    if pss:
        args += ["-sigopt", "rsa_padding_mode:pss", "-sigopt", "rsa_pss_saltlen:32"]
    sig = run(args, doc)
    out.append(c_bytes(f"rsa_{name}_n", n.to_bytes(bits // 8, "big")))
    out.append(c_bytes(f"rsa_{name}_sig", sig))
    digest = hashlib.new(hash_name, doc).digest()
    out.append(c_bytes(f"rsa_{name}_digest", digest))
    out.append(f"#define rsa_{name}_hash RSA_HASH_{hash_name.upper()}\n")
    out.append(f"#define rsa_{name}_hash_len {hashlib.new(hash_name).digest_size}\n")
pkcs1_names = [name for name, *_, pss in [(c[0], c[5]) for c in rsa_cases] if not pss]
pss_names = [c[0] for c in rsa_cases if c[5]]
out.append("#define RSA_PKCS1_CASES(X) " + " ".join(f"X({n})" for n in pkcs1_names) + "\n")
out.append("#define RSA_PSS_CASES(X) " + " ".join(f"X({n})" for n in pss_names) + "\n")
out.append(c_bytes("rsa_wrong_n", wrong_n.to_bytes(256, "big")))
out.append("#define RSA_E 65537u\n")

# ------------------------------------------------------------------ ECDSA
ec_cases = []       # (name, curve_cli, curve_id, openssl_name, hash, bits)
ec_curves = [("p256", "prime256v1", 0, "sha256", 32),
             ("p384", "secp384r1", 1, "sha384", 48)]
for tag, cli, cid, hash_name, cbytes in ec_curves:
    key = os.path.join(WORK, f"{tag}.pem")
    run(["ecparam", "-name", cli, "-genkey", "-noout", "-out", key])
    pubtxt = text(["ec", "-in", key, "-pubout", "-text", "-noout"])
    # "pub:" followed by colon-separated hex lines until a blank line
    lines = pubtxt.splitlines()
    start = next(i for i, l in enumerate(lines) if l.strip().startswith("pub:"))
    hexbuf = lines[start].split("pub:")[1]
    i = start + 1
    while i < len(lines):
        s = lines[i].strip()
        if not s or not all(ch in "0123456789abcdefABCDEF:" for ch in s):
            break
        hexbuf += lines[i]
        i += 1
    pub = bytes.fromhex("".join(hexbuf.replace(":", "").split()))
    sig = run(["dgst", f"-{hash_name}", "-sign", key], doc)
    # split DER: SEQUENCE { r INTEGER, s INTEGER }
    def der_ints(data):
        assert data[0] == 0x30
        length, off = data[1], 2
        if length & 0x80:
            n_len = length & 0x7f
            length = int.from_bytes(data[2:2 + n_len], "big")
            off = 2 + n_len
        vals = []
        while off < 2 + length:
            assert data[off] == 0x02
            off += 1
            il = data[off]
            off += 1
            if il & 0x80:
                nl = il & 0x7f
                il = int.from_bytes(data[off:off + nl], "big")
                off += nl
            v = int.from_bytes(data[off:off + il], "big")
            off += il
            vals.append(v)
        return vals
    r, s = der_ints(sig)
    out.append(c_bytes(f"ec_{tag}_pub", pub))
    out.append(c_bytes(f"ec_{tag}_r", r.to_bytes(cbytes, "big")))
    out.append(c_bytes(f"ec_{tag}_s", s.to_bytes(cbytes, "big")))
    digest = hashlib.new(hash_name, doc).digest()
    out.append(c_bytes(f"ec_{tag}_digest", digest))
    out.append(c_bytes(f"ec_{tag}_order",
                       (int.from_bytes(bytes.fromhex(
                           "ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551"), "big")
                        if cid == 0 else
                        int.from_bytes(bytes.fromhex(
                            "ffffffffffffffffffffffffffffffffffffffffffffffffc7634d81f4372ddf581a0db248b0a77aecec196accc52973"), "big")
                       ).to_bytes(cbytes, "big")))
    # negative material: r with one flipped byte, s = 0, s = order (out of range)
    bad_r = bytearray(r.to_bytes(cbytes, "big"))
    bad_r[0] ^= 0x01
    out.append(c_bytes(f"ec_{tag}_bad_r", bytes(bad_r)))
    out.append(c_bytes(f"ec_{tag}_zero", bytes(cbytes)))
    out.append(c_bytes(f"ec_{tag}_order_plus", (int.from_bytes(
        bytes.fromhex("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551"
                      if cid == 0 else
                      "ffffffffffffffffffffffffffffffffffffffffffffffffc7634d81f4372ddf581a0db248b0a77aecec196accc52973"),
        "big")).to_bytes(cbytes, "big")))
    out.append(f"#define ec_{tag}_id ECDSA_CURVE_P{tag[1:]}\n")
out.append("#define EC_CASES(X) " + " ".join(f"X({t[0]})" for t in ec_curves) + "\n")

print("".join(out))
