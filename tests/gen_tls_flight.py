#!/usr/bin/env python3
"""Record server handshake flights for tests/test_tls_verify.c.

A deterministic build of tests/tls_probe.c (fixed client randomness)
connects to Python's TLS 1.3 server twice (ECDSA P-256 chain, RSA-PSS
chain from tests/x509_fixtures.py) and dumps what the server sent. The
replay test feeds those bytes back to net/tls.c, then re-encrypts edited
flights (no Certificate, bad CertificateVerify, PKCS#1 scheme, ...) with
the handshake secret the client derived, and checks each is refused.
Created by Jonas Lee.
Run: python3 -I tests/gen_tls_flight.py > tests/tls_flight.h
"""
import os
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import test_tls_local as local  # noqa: E402
import x509_fixtures as fx  # noqa: E402


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


work = tempfile.mkdtemp(prefix="ojjy-flight-")
now = int(time.time())
stamp = lambda t: time.strftime("%Y%m%d%H%M%SZ", time.gmtime(t))     # noqa: E731
pki = fx.build(os.path.join(work, "pki"), stamp(now - 86400), stamp(now + 3650 * 86400))
c = pki.certs
roots_pem = os.path.join(work, "roots.pem")
with open(roots_pem, "w") as f:
    for name in ("root_a", "root_b"):
        f.write(open(c[name].pem).read())
src = os.path.join(ROOT, "kernel", "src")
crypto = [os.path.join(src, "crypto", n + ".c") for n in
          ("x509", "x509_chain", "sha256", "sha512", "bignum", "rsa", "ecdsa", "x25519", "aes_gcm", "chacha_poly")]
roots_c = os.path.join(work, "roots.c")
with open(roots_c, "w") as f:
    subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools", "mkroots.py"), "--all", "--pem", roots_pem],
                   stdout=f, check=True, stderr=subprocess.DEVNULL)
probe = os.path.join(work, "probe")
subprocess.run(["clang", "-O1", "-w", "-fno-builtin", "-DTLS_PROBE_FIXED_RANDOM", f"-I{src}",
                os.path.join(HERE, "tls_probe.c"), os.path.join(src, "net", "tls.c"), roots_c,
                os.path.join(src, "string.c")] + crypto + ["-o", probe], check=True)

out = ["/* Generated by tests/gen_tls_flight.py - do not edit. Created by Jonas Lee.\n"
       f" * Server flights recorded {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(now))}. */\n",
       "#include \"crypto/x509.h\"\n", f"#define FLIGHT_NOW {now}LL\n",
       c_bytes("flight_root_a", c["root_a"].der), c_bytes("flight_root_b", c["root_b"].der)]
for name, chain, host in [("ecdsa", ("leaf_a", "int_a"), "www.example.test"),
                          ("rsa", ("leaf_b", "int_b"), "rsa.example.test")]:
    pem = os.path.join(work, name + ".pem")
    with open(pem, "w") as f:
        for n in chain:
            f.write(open(c[n].pem).read())
    server = local.serve(pem, c[chain[0]].key)
    record = os.path.join(work, name + ".bin")
    try:
        got = subprocess.run([probe, "-r", record, "127.0.0.1", str(server.server_address[1]), host],
                             capture_output=True, text=True, timeout=60).stdout
    finally:
        server.shutdown()
        server.server_close()
    if "verified=1" not in got:
        sys.exit(f"gen_tls_flight: {name} handshake did not verify: {got}")
    out.append(c_bytes(f"flight_{name}", open(record, "rb").read()))
    out.append(f"#define FLIGHT_{name.upper()}_HOST \"{host}\"\n")
# the replay test's trust store: the two fixture roots, in mkroots form
out.append(open(roots_c).read().split('#include "crypto/x509.h"', 1)[1])
sys.stdout.write("".join(out))
