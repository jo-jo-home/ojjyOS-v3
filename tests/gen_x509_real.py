#!/usr/bin/env python3
"""Capture real HTTPS certificate chains once into tests/x509_real.h, so
tests/test_x509.c can check the built-in roots (roots_data.c) against what
big sites really send, at the fixed capture time (needs internet; the
certificates are public, logged in Certificate Transparency).
Created by Jonas Lee.
Run: python3 -I tests/gen_x509_real.py > tests/x509_real.h
"""
import base64
import re
import subprocess
import sys
import time

HOSTS = ["en.wikipedia.org", "text.npr.org", "example.com", "github.com", "www.apple.com", "www.google.com"]


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


now = int(time.time())
out = ["/* Generated by tests/gen_x509_real.py - do not edit. Created by Jonas Lee.\n"
       f" * Real chains captured {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(now))}. */\n",
       "#include \"types.h\"\n", f"#define X509_REAL_NOW {now}LL\n"]
entries = []
for i, host in enumerate(HOSTS):
    text = subprocess.run(["openssl", "s_client", "-showcerts", "-servername", host, "-connect", f"{host}:443"],
                          input=b"", capture_output=True, timeout=30).stdout.decode("latin-1")
    blocks = re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", text, re.S)[:4]
    if not blocks:
        sys.exit(f"gen_x509_real: no certificates from {host}")
    names = []
    for j, block in enumerate(blocks):
        out.append(c_bytes(f"real{i}_{j}", base64.b64decode("".join(block.split()))))
        names.append(f"{{real{i}_{j}, sizeof(real{i}_{j})}}")
    out.append(f"static const X509Span real{i}[] = {{{', '.join(names)}}};\n")
    entries.append(f"    {{\"{host}\", real{i}, {len(blocks)}}},\n")
out.append("static const struct { const char *host; const X509Span *certs; size_t count; } x509_real[] = {\n"
           + "".join(entries) + "};\n")
sys.stdout.write("".join(out))
