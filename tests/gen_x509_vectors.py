#!/usr/bin/env python3
"""Generate tests/x509_vectors.h: real DER certificates from the OpenSSL CLI
(tests/x509_fixtures.py) plus TLS 1.3 CertificateVerify signatures made with
the leaf keys. Created by Jonas Lee.
Run: python3 -I tests/gen_x509_vectors.py > tests/x509_vectors.h
"""
import os
import random
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import x509_fixtures as fx  # noqa: E402

rng = random.Random(20261027)
WORK = tempfile.mkdtemp(prefix="ojjy-x509-")


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows) or "0"
    return f"static const uint8_t {name}[] = {{\n    {body}\n}};\nstatic const size_t {name}_len = {len(data)};\n"


KEY_CONST = {"rsa1024": ("X509_KEY_RSA", 1024), "rsa2048": ("X509_KEY_RSA", 2048),
             "rsa3072": ("X509_KEY_RSA", 3072), "rsa4096": ("X509_KEY_RSA", 4096),
             "p256": ("X509_KEY_EC_P256", 256), "p384": ("X509_KEY_EC_P384", 384)}

pki = fx.build(WORK)
out = ["/* Generated by tests/gen_x509_vectors.py - do not edit. Created by Jonas Lee. */\n",
       "#include \"types.h\"\n",
       f"#define X509_TEST_NOW {fx.unix('20270101000000Z')}LL   /* 2027-01-01, inside every valid window */\n"]
names = list(pki.certs)
out.append("#define X509_CERTS(X) " + " ".join(f"X({n})" for n in names) + "\n")
for name, cert in pki.certs.items():
    key, bits = KEY_CONST[cert.key_kind]
    up = name.upper()
    out.append(c_bytes(f"x509_{name}", cert.der))
    out.append(f"#define X509_{up}_NB {cert.not_before}LL\n#define X509_{up}_NA {cert.not_after}LL\n"
               f"#define X509_{up}_SIG {cert.sig}\n#define X509_{up}_KEY {key}\n#define X509_{up}_BITS {bits}\n"
               f"#define X509_{up}_CN \"{cert.cn}\"\n")

# TLS 1.3 CertificateVerify (RFC 8446 4.4.3) over a fixed transcript hash.
th = bytes(rng.randrange(256) for _ in range(32))
content = b" " * 64 + b"TLS 1.3, server CertificateVerify" + b"\x00" + th
out.append(c_bytes("cv_transcript", th))
cases = [("ecdsa_p256", "leaf_a", "sha256", False), ("ecdsa_p384", "leaf_c", "sha384", False),
         ("pss256", "leaf_b", "sha256", True), ("pss384", "leaf_b", "sha384", True),
         ("pss512", "leaf_b", "sha512", True), ("pkcs1", "leaf_b", "sha256", False)]
for case, leaf, digest, pss in cases:
    args = ["dgst", f"-{digest}", "-sign", pki.certs[leaf].key]
    if pss:
        args += ["-sigopt", "rsa_padding_mode:pss", "-sigopt", "rsa_pss_saltlen:digest"]
    out.append(c_bytes(f"cv_sig_{case}", fx.openssl(*args, data=content)))
sys.stdout.write("".join(out))
