/*
 * mkarray - generate a C header embedding a binary file.
 *
 * Replaces the old `xxd -i | sed` pipeline, which produced variable names
 * derived from the full input path (breaking the kernel build whenever the
 * repository was not at the expected location).
 *
 * Usage: mkarray <input-file> <output-header> <array-name>
 *
 * Emits:
 *   static const uint8_t <array-name>[] = { ... };
 *   static const unsigned long <array-name>_len = <size>;
 *
 * ojjyOS - Created by Jonas Lee
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: %s <input-file> <output-header> <array-name>\n",
                argv[0]);
        return 1;
    }

    const char *in_path = argv[1];
    const char *out_path = argv[2];
    const char *name = argv[3];

    if (strlen(name) == 0 || strchr(name, '[') || strchr(name, ']') ||
        strchr(name, ';') || strchr(name, ' ')) {
        fprintf(stderr, "%s: invalid array name '%s'\n", argv[0], name);
        return 1;
    }

    FILE *in = fopen(in_path, "rb");
    if (!in) {
        fprintf(stderr, "%s: cannot open '%s'\n", argv[0], in_path);
        return 1;
    }

    FILE *out = fopen(out_path, "w");
    if (!out) {
        fprintf(stderr, "%s: cannot open '%s' for writing\n", argv[0], out_path);
        fclose(in);
        return 1;
    }

    fprintf(out, "/*\n");
    fprintf(out, " * Generated by tools/mkarray - do not edit.\n");
    fprintf(out, " * Embeds: %s\n", in_path);
    fprintf(out, " */\n\n");
    /* Use builtin types only: this header is compiled inside the
     * freestanding kernel, which provides its own fixed-width types. */
    fprintf(out, "static const unsigned char %s[] = {\n    ", name);

    unsigned long total = 0;
    int byte;
    int col = 0;

    while ((byte = fgetc(in)) != EOF) {
        if (col == 0 && total > 0) {
            fprintf(out, "\n    ");
        }
        fprintf(out, "0x%02x,", byte);
        total++;
        if (++col == 16) col = 0;
    }

    if (ferror(in)) {
        fprintf(stderr, "%s: error reading '%s'\n", argv[0], in_path);
        fclose(in);
        fclose(out);
        return 1;
    }

    fprintf(out, "\n};\n\n");
    fprintf(out, "static const unsigned long %s_len = %lu;\n", name, total);

    fclose(in);
    if (fclose(out) != 0) {
        fprintf(stderr, "%s: error writing '%s'\n", argv[0], out_path);
        return 1;
    }

    printf("%s: embedded %lu bytes as '%s'\n", argv[0], total, name);
    return 0;
}
