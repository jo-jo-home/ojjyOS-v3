#!/usr/bin/env python3
"""mkcursor.py - render the ojjyOS pointer (anti-aliased macOS-style arrow:
white fill, dark outline, soft drop shadow) into kernel/src/cursor_image.c.

Rendered at 8x supersampling and downsampled, so the edges are smooth.
Output: CURSOR_W x CURSOR_H straight-alpha RGBA, hotspot at (CURSOR_HOT_X, Y).

Usage: python3 tools/mkcursor.py kernel/src/cursor_image.c
ojjyOS - Created by Jonas Lee
"""
import sys
from PIL import Image, ImageDraw, ImageFilter

W, H, SS = 22, 30, 8
HOT = (2, 2)
# Arrow outline in 1x pixel units (tip at the hotspot)
ARROW = [(0, 0), (0, 17.5), (4.3, 13.6), (7.2, 20.2), (9.9, 19.0), (7.1, 12.6), (12.8, 12.6)]

SCALE = 1.12

K = 1          # density: 1x or 2x (set by render())

def poly(offset=(0, 0)):
    return [((HOT[0] + x * SCALE + offset[0]) * SS * K, (HOT[1] + y * SCALE + offset[1]) * SS * K) for x, y in ARROW]

def render(k):
    global K
    K = k
    big = (W * SS * k, H * SS * k)
    shadow = Image.new("L", big, 0)
    sd = ImageDraw.Draw(shadow)
    sd.polygon(poly((0.3, 1.1)), fill=255)
    sd.line(poly((0.3, 1.1)) + [poly((0.3, 1.1))[0]], fill=255, width=int(1.4 * SS * k), joint="curve")
    shadow = shadow.filter(ImageFilter.GaussianBlur(1.5 * SS * k))
    shape = Image.new("L", big, 0)       # outer silhouette: fill + outline stroke
    d = ImageDraw.Draw(shape)
    d.polygon(poly(), fill=255)
    d.line(poly() + [poly()[0]], fill=255, width=int(1.5 * SS * k), joint="curve")
    inner = Image.new("L", big, 0)       # white body: fill minus the stroke
    ImageDraw.Draw(inner).polygon(poly(), fill=255)
    stroke = Image.new("L", big, 0)
    ImageDraw.Draw(stroke).line(poly() + [poly()[0]], fill=255, width=int(1.5 * SS * k), joint="curve")
    inner = Image.composite(Image.new("L", big, 0), inner, stroke)

    img = Image.new("RGBA", big, (0, 0, 0, 0))
    img.paste((0, 0, 0, 255), (0, 0), shadow.point(lambda v: v * 90 // 255))
    img.paste((18, 22, 30, 255), (0, 0), shape)
    img.paste((255, 255, 255, 255), (0, 0), inner)
    # Downsample premultiplied to avoid dark/light fringes.
    r, g, b, a = img.split()
    pm = Image.merge("RGBA", [Image.composite(c, Image.new("L", big, 0), a) for c in (r, g, b)] + [a])
    small = pm.resize((W * k, H * k), Image.LANCZOS)
    data = []
    pixels = getattr(small, "get_flattened_data", small.getdata)()
    for (pr, pg, pb, pa) in pixels:
        if pa:
            pr, pg, pb = (min(255, pr * 255 // pa), min(255, pg * 255 // pa), min(255, pb * 255 // pa))
        data += [pr, pg, pb, pa]
    return data

def main(out_path):
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/mkcursor.py - do not edit. ojjyOS - Created by Jonas Lee */\n")
        f.write('#include "cursor_image.h"\n\n')
        for k, name in ((1, "cursor_rgba"), (2, "cursor_rgba2x")):
            data = render(k)
            f.write("const uint8_t %s[CURSOR_W * CURSOR_H * 4 * %d] = {\n" % (name, k * k))
            for i in range(0, len(data), 16):
                f.write("    " + ", ".join(str(v) for v in data[i:i + 16]) + ",\n")
            f.write("};\n")

if __name__ == "__main__":
    main(sys.argv[1])
