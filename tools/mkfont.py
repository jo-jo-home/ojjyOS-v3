#!/usr/bin/env python3
"""
mkfont.py - generate the ojjyOS anti-aliased console font.

Renders JetBrains Mono (SIL Open Font License 1.1) into an 8x16
monospace cell grid at 4x supersampling, then downsamples with LANCZOS
for smooth grayscale coverage values. The result is a C array of
95 glyphs (ASCII 32..126), 128 bytes per glyph (8 wide x 16 tall,
one coverage byte per pixel).

Usage: python3 tools/mkfont.py fonts/JetBrainsMono-Regular.ttf kernel/src/font.c

ojjyOS - Created by Jonas Lee
"""

import sys
from PIL import Image, ImageFont, ImageDraw

CELL_W, CELL_H = 8, 16
SS = 4                      # supersample factor
SS_W, SS_H = CELL_W * SS, CELL_H * SS
FIRST, LAST = 32, 126
NGlyphs = LAST - FIRST + 1

def render_at_size(font_path, em_px):
    """Render all glyphs at `em_px` size, return list of (mask, baseline) tuples."""
    font = ImageFont.truetype(font_path, em_px)
    glyphs = []
    ascent, descent = font.getmetrics()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        # Render the glyph mask (grayscale) on a supersampled canvas
        img = Image.new("L", (SS_W * 2, SS_H * 2), 0)
        draw = ImageDraw.Draw(img)
        try:
            bbox = draw.textbbox((0, 0), ch, font=font)
        except Exception:
            bbox = (0, 0, 0, 0)
        # Place with left bearing at x=0, cap top aligned to ascent
        draw.text((-bbox[0], 0), ch, font=font, fill=255)
        # Crop to the cell: top of cell = ascent baseline zone
        # We align the glyph so the baseline sits at a fixed row.
        glyphs.append((img, ascent, descent, bbox))
    return glyphs

def build(font_path):
    # Target advance of 8 px on the final 8x16 cell. JetBrains Mono
    # advance = 0.6 em -> em ~ 13.3px. Supersample x4 -> ~53px.
    em = 13.3
    font = ImageFont.truetype(font_path, int(round(em * SS)))
    ascent, descent = font.getmetrics()

    # Baseline (in supersampled pixels) placed so glyphs sit centered
    # vertically in the 16px cell: cap area above baseline, small
    # descender room below.
    baseline_ss = int(round((CELL_H - 3.5) * SS))   # baseline at row ~12.5 final

    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        canvas = Image.new("L", (SS_W, SS_H), 0)
        draw = ImageDraw.Draw(canvas)
        # Get glyph bbox at origin to align left bearing
        try:
            bbox = draw.textbbox((0, 0), ch, font=font)
        except Exception:
            bbox = (0, baseline_ss, 0, baseline_ss)
        draw_x = -bbox[0]                 # left bearing -> x=0
        draw_y = baseline_ss - ascent      # PIL text origin is the ascent top
        draw.text((draw_x, draw_y), ch, font=font, fill=255)
        # Downsample to the final 8x16 cell
        cell = canvas.resize((CELL_W, CELL_H), Image.LANCZOS)
        out.append(list(cell.getdata()))

    return out

def emit(glyphs, out_path):
    with open(out_path, "w") as f:
        f.write("/*\n")
        f.write(" * ojjyOS v3 Kernel - Console Font\n")
        f.write(" *\n")
        f.write(" * Anti-aliased 8x16 monospace font, ASCII 32..126.\n")
        f.write(" * Generated by tools/mkfont.py from JetBrains Mono\n")
        f.write(" * (SIL Open Font License 1.1 - see fonts/OFL-LICENSE.txt).\n")
        f.write(" * Each glyph is 128 coverage bytes (8x16, 0 = background,\n")
        f.write(" * 255 = foreground), blended per pixel by fb_draw_char().\n")
        f.write(" *\n")
        f.write(" * ojjyOS - Created by Jonas Lee\n")
        f.write(" */\n\n")
        f.write('#include "font.h"\n\n')
        f.write("#define FONT_AA_GLYPHS  95\n\n")
        f.write("static const uint8_t font_aa[FONT_AA_GLYPHS][FONT_WIDTH * FONT_HEIGHT] = {\n")
        for gi, px in enumerate(glyphs):
            code = FIRST + gi
            f.write("    /* %s (%d) */\n    {" % (repr(chr(code))[1:-1].replace("\\", "\\\\"), code))
            for i, v in enumerate(px):
                if i % 16 == 0:
                    f.write("\n    ")
                f.write("%3d," % v)
            f.write("\n    },\n")
        f.write("};\n\n")
        f.write("""/*
 * Get the anti-aliased coverage bitmap for a character
 * (FONT_WIDTH * FONT_HEIGHT bytes, 0..255 per pixel).
 */
const uint8_t *font_get_glyph_aa(char c)
{
    uint8_t ch = (uint8_t)c;
    if (ch < 32 || ch > 126) {
        ch = '?';
    }
    return font_aa[ch - 32];
}
""")
    print("wrote", out_path, "-", NGlyphs, "glyphs")

def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    glyphs = build(sys.argv[1])
    # Sanity: report coverage of a few glyphs
    for name, code in [("A", 65), ("a", 97), ("m", 109), ("~", 126), (" ", 32)]:
        g = glyphs[code - FIRST]
        print(name, "max coverage:", max(g), "nonzero px:", sum(1 for v in g if v > 8))
    emit(glyphs, sys.argv[2])

if __name__ == "__main__":
    main()
