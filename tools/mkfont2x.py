#!/usr/bin/env python3
"""mkfont2x.py - 16x32 (2x HiDPI) version of the JetBrains Mono console font.

Same glyph design as tools/mkfont.py (SIL OFL 1.1, fonts/OFL-LICENSE.txt),
rendered at twice the size for Retina-density displays.
Usage: python3 tools/mkfont2x.py fonts/JetBrainsMono-Regular.ttf kernel/src/font2x.c
ojjyOS - Created by Jonas Lee
"""
import sys
from PIL import Image, ImageFont, ImageDraw

W, H, SS = 16, 32, 4
FIRST, LAST = 32, 126

def main(font_path, out_path):
    font = ImageFont.truetype(font_path, int(round(13.3 * 2 * SS)))
    ascent, _ = font.getmetrics()
    baseline = int(round((H - 7) * SS))
    rows = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        canvas = Image.new("L", (W * SS, H * SS), 0)
        d = ImageDraw.Draw(canvas)
        bbox = d.textbbox((0, 0), ch, font=font)
        d.text((-bbox[0] if code != 32 else 0, baseline - ascent), ch, font=font, fill=255)
        rows.append(list(canvas.resize((W, H), Image.LANCZOS).tobytes()))
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/mkfont2x.py from JetBrains Mono (SIL OFL 1.1).\n")
        f.write(" * 16x32 coverage glyphs for 2x displays. ojjyOS - Created by Jonas Lee */\n")
        f.write('#include "font.h"\n\n')
        f.write("static const uint8_t font_aa2x[95][FONT_WIDTH * FONT_HEIGHT * 4] = {\n")
        for code, px in zip(range(FIRST, LAST + 1), rows):
            f.write("    { /* %d */\n" % code)
            for i in range(0, len(px), 32):
                f.write("     " + ",".join(str(v) for v in px[i:i + 32]) + ",\n")
            f.write("    },\n")
        f.write("};\n\n")
        f.write("const uint8_t *font_get_glyph_aa2x(char c)\n{\n")
        f.write("    uint8_t ch = (uint8_t)c;\n    if (ch < 32 || ch > 126) ch = '?';\n")
        f.write("    return font_aa2x[ch - 32];\n}\n")
    print("wrote", out_path)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
