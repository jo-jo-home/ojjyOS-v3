#!/usr/bin/env python3
"""
mkuifont.py - generate the ojjyOS proportional UI fonts (kernel/src/uifont_data.c).

Renders Inter (SIL Open Font License 1.1, (c) The Inter Project Authors,
fonts/Inter-OFL-LICENSE.txt) into anti-aliased 8-bit coverage bitmaps for a
fixed set of text styles, each at 1x and 2x (HiDPI) pixel density.

Per glyph: codepoint, bitmap size, left bearing, top (pixels above the
baseline) and advance in 1/64 px (fractional advances keep word spacing
even). Coverage gets a mild gamma lift so small text isn't thin.

Usage: python3 tools/mkuifont.py kernel/src/uifont_data.c
ojjyOS - Created by Jonas Lee
"""
import sys
from pathlib import Path
from PIL import Image, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"

ASCII = [chr(c) for c in range(32, 127)]
EXTRAS = ["•", "—", "–", "…", "←", "→", "↑", "↓",
          "©", "°", "·", "⌘", "✓", "×", "⌥", "⇧", "é",
          "÷", "−", "±", "⌫", "‹", "›", "⌃"]
DIGITS = list(" 0123456789:APM")
# Web pages: Latin-1 letters and the common typographic characters, only in
# the styles the browser uses for page text (keeps the kernel image small).
WEB = [chr(c) for c in range(0xA1, 0x100) if c not in (0xAD,)] + \
      ["\u2018", "\u2019", "\u201a", "\u201c", "\u201d", "\u201e", "\u20ac", "\u2122", "\u2032", "\u2033",
       "\u2264", "\u2265", "\u2260", "\u2248", "\u2039", "\u203a", "\u2020", "\u2021", "\u2030"]

# (enum name, file, px size, charset)
STYLES = [
    ("TEXT_SMALL",       "Inter-Regular.ttf",  11, ASCII + EXTRAS),
    ("TEXT_SMALL_BOLD",  "Inter-SemiBold.ttf", 11, ASCII + EXTRAS),
    ("TEXT_BODY",        "Inter-Regular.ttf",  13, ASCII + EXTRAS + WEB),
    ("TEXT_BODY_MEDIUM", "Inter-Medium.ttf",   13, ASCII + EXTRAS),
    ("TEXT_BODY_BOLD",   "Inter-SemiBold.ttf", 13, ASCII + EXTRAS + WEB),
    ("TEXT_TITLE",       "Inter-SemiBold.ttf", 15, ASCII + EXTRAS + WEB),
    ("TEXT_HEADLINE",    "Inter-Bold.ttf",     20, ASCII + EXTRAS + WEB),
    ("TEXT_LARGE",       "Inter-SemiBold.ttf", 28, ASCII + EXTRAS + WEB),
    ("TEXT_DISPLAY",     "Inter-Medium.ttf",   72, DIGITS),
]
GAMMA = 0.85     # < 1 lifts mid coverage (slightly bolder, crisper strokes)


def missing_mask(font):
    m = font.getmask("￿", mode="L")
    return m.size, bytes(m)


def render_style(path, px, chars):
    font = ImageFont.truetype(str(path), px)
    precise = ImageFont.truetype(str(path), px * 16)
    ascent, descent = font.getmetrics()
    notdef = missing_mask(font)
    glyphs, bitmap = [], bytearray()
    for ch in chars:
        cp = ord(ch)
        mask = font.getmask(ch, mode="L")
        if cp > 127 and (mask.size, bytes(mask)) == notdef:
            continue                                  # not in the font
        adv64 = round(precise.getlength(ch) * 64 / 16)
        if ch == " ":
            glyphs.append((cp, 0, 0, 0, 0, adv64, len(bitmap)))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")   # relative to left/baseline
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        if w > 0 and h > 0:
            from PIL import ImageDraw
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        data = bytes(int(255 * ((v / 255) ** GAMMA) + 0.5) for v in img.tobytes()) if w > 0 and h > 0 else b""
        glyphs.append((cp, x0, -y0, w if data else 0, h if data else 0, adv64, len(bitmap)))
        bitmap += data
    line = round(px * 1.3)
    return {"ascent": ascent, "descent": descent, "line": line, "glyphs": glyphs, "bitmap": bytes(bitmap)}


def main(out_path):
    out = ["/* Generated by tools/mkuifont.py from Inter (SIL OFL 1.1, (c) The Inter",
           " * Project Authors). Do not edit. ojjyOS - Created by Jonas Lee */",
           '#include "uifont.h"', ""]
    faces = []
    for name, file, px, chars in STYLES:
        for scale in (1, 2):
            f = render_style(FONTS / file, px * scale, chars)
            tag = f"{name.lower()}_{scale}x"
            out.append(f"static const UiGlyph {tag}_glyphs[] = {{")
            for (cp, bx, top, w, h, adv, off) in f["glyphs"]:
                out.append(f"    {{ {cp}, {bx}, {top}, {w}, {h}, {adv}, {off} }},")
            out.append("};")
            out.append(f"static const uint8_t {tag}_bits[] = {{")
            b = f["bitmap"] or b"\0"
            for i in range(0, len(b), 24):
                out.append("    " + ",".join(str(v) for v in b[i:i + 24]) + ",")
            out.append("};")
            faces.append((name, scale, tag, f))
    out.append("")
    out.append("const UiFontFace uifont_faces[TEXT_STYLE_COUNT][2] = {")
    by_name = {}
    for name, scale, tag, f in faces:
        by_name.setdefault(name, []).append(
            f"{{ {tag}_glyphs, {len(f['glyphs'])}, {tag}_bits, {f['ascent']}, {f['descent']}, {f['line']} }}")
    for name, _, _, _ in STYLES:
        out.append(f"    [{name}] = {{ {', '.join(by_name[name])} }},")
    out.append("};")
    Path(out_path).write_text("\n".join(out) + "\n")
    total = sum(len(f["bitmap"]) for *_, f in faces)
    print(f"{len(faces)} faces, {total // 1024} KB of glyph bitmaps -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1])
