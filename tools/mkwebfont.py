#!/usr/bin/env python3
"""
mkwebfont.py - generate the web page faces (kernel/src/webfont_data.c).

Web pages ask for many font sizes; the browser picks the nearest of these
faces: Inter Regular and Bold (SIL OFL 1.1, (c) The Inter Project Authors)
and JetBrains Mono (SIL OFL 1.1) for code, each at 1x and 2x density.
Glyph rendering is shared with tools/mkuifont.py.

Usage: python3 tools/mkwebfont.py kernel/src/webfont_data.c
ojjyOS - Created by Jonas Lee
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from mkuifont import render_style, ASCII, EXTRAS, WEB, FONTS  # noqa: E402

SIZES = [12, 13, 14, 15, 16, 18, 20, 24, 28, 32]
MONO_SIZES = [13, 16]
CHARS = ASCII + EXTRAS + WEB


def pack4(f):
    """Repack 8-bit coverage into 4-bit nibbles (high nibble first); each
    glyph starts on a byte boundary. Fills f["glyphs4"] with new offsets."""
    out = bytearray()
    glyphs = []
    for (cp, bx, top, w, h, adv, off) in f["glyphs"]:
        n = w * h
        src = f["bitmap"][off:off + n]
        start = len(out)
        for i in range(0, n, 2):
            hi = (src[i] * 15 + 127) // 255
            lo = (src[i + 1] * 15 + 127) // 255 if i + 1 < n else 0
            out.append((hi << 4) | lo)
        glyphs.append((cp, bx, top, w, h, adv, start))
    f["glyphs4"] = glyphs
    return bytes(out) or b"\0"


def main(out_path):
    faces = []
    for px in SIZES:
        faces.append((f"r{px}", "Inter-Regular.ttf", px))
        faces.append((f"b{px}", "Inter-Bold.ttf", px))
    for px in MONO_SIZES:
        faces.append((f"m{px}", "JetBrainsMono-Regular.ttf", px))
    out = ["/* Generated by tools/mkwebfont.py from Inter and JetBrains Mono (SIL OFL 1.1).",
           " * Do not edit. ojjyOS - Created by Jonas Lee */",
           '#include "webfont.h"', ""]
    table = []
    total = 0
    for tag, file, px in faces:
        row = []
        for scale in (1, 2):
            f = render_style(FONTS / file, px * scale, CHARS)
            packed = pack4(f)
            name = f"wf_{tag}_{scale}x"
            out.append(f"static const UiGlyph {name}_glyphs[] = {{")
            for (cp, bx, top, w, h, adv, off) in f["glyphs4"]:
                out.append(f"    {{ {cp}, {bx}, {top}, {w}, {h}, {adv}, {off} }},")
            out.append("};")
            out.append(f"static const uint8_t {name}_bits[] = {{")
            b = packed
            total += len(b)
            for i in range(0, len(b), 32):
                out.append("    " + ",".join(str(v) for v in b[i:i + 32]) + ",")
            out.append("};")
            row.append(f"{{ {name}_glyphs, {len(f['glyphs'])}, {name}_bits, {f['ascent']}, {f['descent']}, {f['line']}, 1 }}")
        table.append(f"    {{ {', '.join(row)} }},")
    out.append("")
    out.append(f"const uint8_t webfont_sizes[WEBFONT_SIZES] = {{ {', '.join(str(s) for s in SIZES)} }};")
    out.append(f"const uint8_t webfont_mono_sizes[WEBFONT_MONO_SIZES] = {{ {', '.join(str(s) for s in MONO_SIZES)} }};")
    out.append("/* [size*2 + bold] for Inter, then the mono faces */")
    out.append("const UiFontFace webfont_faces[WEBFONT_FACES][2] = {")
    out += table
    out.append("};")
    Path(out_path).write_text("\n".join(out) + "\n")
    print(f"{len(faces)} faces x2, {total // 1024} KB of glyph bitmaps -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1])
